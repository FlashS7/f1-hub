// Generates src/data/circuits.ts: SVG outline paths from the MIT-licensed
// bacinger/f1-circuits GeoJSON. Run: node scripts/build-circuits.mjs
import { writeFileSync } from "node:fs";

const MAP = {
  albert_park: "au-1953", shanghai: "cn-2004", suzuka: "jp-1962", bahrain: "bh-2002",
  jeddah: "sa-2021", miami: "us-2022", villeneuve: "ca-1978", monaco: "mc-1929",
  catalunya: "es-1991", red_bull_ring: "at-1969", silverstone: "gb-1948", spa: "be-1925",
  hungaroring: "hu-1986", zandvoort: "nl-1948", monza: "it-1922", madring: "es-2026",
  baku: "az-2016", sepang: "my-1999", marina_bay: "sg-2008", americas: "us-2012",
  rodriguez: "mx-1962", interlagos: "br-1940", vegas: "us-2023", losail: "qa-2004",
  yas_marina: "ae-2009", imola: "it-1953",
};
const SIZE = 1000;
const PAD = 40;

const out = {};
for (const [id, file] of Object.entries(MAP)) {
  const url = `https://raw.githubusercontent.com/bacinger/f1-circuits/master/circuits/${file}.geojson`;
  const gj = await (await fetch(url)).json();
  const geom = gj.features[0].geometry;
  const coords = geom.type === "LineString" ? geom.coordinates : geom.coordinates.flat();
  const lat0 = coords.reduce((s, c) => s + c[1], 0) / coords.length;
  const k = Math.cos((lat0 * Math.PI) / 180);
  const pts = coords.map(([lon, lat]) => [lon * k, -lat]);
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const scale = (SIZE - 2 * PAD) / Math.max(maxX - minX, maxY - minY);
  const w = (maxX - minX) * scale + 2 * PAD;
  const h = (maxY - minY) * scale + 2 * PAD;
  const d = pts
    .map(([x, y], i) => `${i ? "L" : "M"}${((x - minX) * scale + PAD).toFixed(1)} ${((y - minY) * scale + PAD).toFixed(1)}`)
    .join("");
  out[id] = { w: Math.round(w), h: Math.round(h), d: d + "Z" };
  console.log(id, coords.length, "points");
}

writeFileSync(
  new URL("../src/data/circuits.ts", import.meta.url),
  `// Generated by scripts/build-circuits.mjs from github.com/bacinger/f1-circuits (MIT). Do not edit.\n` +
    `export const CIRCUITS: Record<string, { w: number; h: number; d: string }> = ${JSON.stringify(out)};\n`,
);
